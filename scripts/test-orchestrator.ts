import { db } from "../src/infrastructure/db/client";
import { ConversationOrchestrator } from "../src/core/pipeline/ConversationOrchestrator";

async function run() {
  console.log("Starting simulation test...");
  
  const orchestrator = new ConversationOrchestrator();
  
  try {
    const result = await orchestrator.handle({
      clinicId: "d24a584a-faac-4a46-9750-a718d0f8e686", // Vitalli
      phone: "5511" + Math.floor(Math.random() * 100000000).toString().padStart(8, '0'),
      messageText: "Olá! vi o anúncio e quero saber como posso transformar meu sorriso com facetas de resina?",
      messageId: "fake-msg-" + Date.now(),
      senderName: "Amanda Lead",
      timestamp: new Date(),
    });
    
    // Fetch the inserted messages to see what it generated
    const { messages } = await import("../src/infrastructure/db/schema");
    const { eq, desc } = await import("drizzle-orm");
    const recentMsgs = await db.select().from(messages).orderBy(desc(messages.createdAt)).limit(3);
    console.log("Recent messages generated by AI:");
    recentMsgs.forEach(m => console.log(`[${m.author}] ${m.body}`));
    
    console.log("Orchestrator finished:", result);
  } catch (err) {
    console.error("Orchestrator threw error:", err);
  }
  
  process.exit(0);
}

run().catch(console.error);
